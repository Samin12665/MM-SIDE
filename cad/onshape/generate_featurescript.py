        skRectangle(sk, "rearBumper", { "firstCorner" : pXY(V(context, "rearBumperX"), -V(context, "bumperWidth") / 2 - 15 * millimeter), "secondCorner" : pXY(-226 * millimeter, V(context, "bumperWidth") / 2 + 15 * millimeter) });
